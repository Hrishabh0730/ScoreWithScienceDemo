import type { Metadata } from "next";
import Image from "next/image";
import Link from "next/link";
import { notFound } from "next/navigation";
import { requireUser } from "@/lib/auth";
import { getSettings } from "@/lib/data";
import { fmtDateTime, inr } from "@/lib/format";
import { ORDER_STATUS_LABEL } from "@/lib/types";
import { PrintButton } from "./PrintButton";

export const metadata: Metadata = { title: "Receipt", robots: { index: false } };

export default async function Receipt({ params }: { params: Promise<{ order: string }> }) {
  const { order: orderNumber } = await params;
  const { supabase, profile, user } = await requireUser("/account");
  const { site } = await getSettings();
  const { data: o } = await supabase
    .from("orders")
    .select("order_number, kind, status, amount_paise, paid_at, created_at, razorpay_payment_id, payment_method, order_items(title_snapshot, price_paise), bookings(booking_number, service, slots(start_at, duration_minutes))")
    .eq("order_number", orderNumber)
    .maybeSingle();
  if (!o || o.status === "created") notFound();
  const booking = (o.bookings as unknown as { booking_number: string; service: string; slots: { start_at: string; duration_minutes: number } }[])?.[0];
  const lines =
    o.kind === "notes"
      ? (o.order_items as { title_snapshot: string; price_paise: number }[]).map((i) => ({ label: `Notes: ${i.title_snapshot}`, amount: i.price_paise }))
      : [{ label: `${booking?.service === "tuition" ? "Chemistry tuition" : "Chemistry doubt session"} (${booking?.slots?.duration_minutes} min) — ${booking?.slots ? fmtDateTime(booking.slots.start_at) : ""} IST · ${booking?.booking_number}`, amount: o.amount_paise }];

  return (
    <div className="container-x max-w-2xl py-10">
      <div className="mb-4 flex justify-between print:hidden">
        <Link href="/account" className="btn-ghost">← My account</Link>
        <PrintButton />
      </div>
      <div className="card p-8 print:border-0 print:shadow-none">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-3">
            <Image src="/logo.png" alt="" width={48} height={48} className="rounded-full" />
            <div>
              <p className="font-extrabold text-navy-900">{site.business_name}</p>
              {site.contact_email && <p className="text-xs text-muted">{site.contact_email}</p>}
            </div>
          </div>
          <p className="text-right text-sm">
            <span className="block font-bold text-navy-900">Payment receipt</span>
            <span className="text-muted">{o.order_number}</span>
          </p>
        </div>
        <dl className="mt-8 grid grid-cols-2 gap-y-2 text-sm">
          <dt className="text-muted">Billed to</dt>
          <dd className="font-semibold">{profile?.full_name} ({user.email})</dd>
          <dt className="text-muted">Date paid</dt>
          <dd className="font-semibold">{o.paid_at ? fmtDateTime(o.paid_at) : "—"}</dd>
          <dt className="text-muted">Payment ID</dt>
          <dd className="font-mono text-xs">{o.razorpay_payment_id ?? "—"}</dd>
          <dt className="text-muted">Method</dt>
          <dd className="font-semibold uppercase">{o.payment_method ?? "—"}</dd>
          <dt className="text-muted">Status</dt>
          <dd className="font-semibold">{ORDER_STATUS_LABEL[o.status] ?? o.status}</dd>
        </dl>
        <table className="table-x mt-8">
          <thead><tr><th>Item</th><th className="text-right">Amount</th></tr></thead>
          <tbody>
            {lines.map((l, i) => (
              <tr key={i}><td>{l.label}</td><td className="text-right">{inr(l.amount)}</td></tr>
            ))}
            <tr><td className="font-bold">Total paid</td><td className="text-right text-lg font-extrabold">{inr(o.amount_paise)}</td></tr>
          </tbody>
        </table>
        <p className="mt-6 text-xs text-muted">This is a payment acknowledgement generated by {site.business_name}. Payments processed by Razorpay.</p>
      </div>
    </div>
  );
}
